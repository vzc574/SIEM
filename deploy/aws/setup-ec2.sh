#!/usr/bin/env bash
# Provision the SIEM on a fresh Ubuntu 24.04 EC2 instance.
#
#   sudo ./setup-ec2.sh --domain siem.example.com --email you@example.com \
#        [--repo https://github.com/vzc574/SIEM.git] [--branch master] [--dir /opt/siem]
#
# Safe to re-run: it updates the code and restarts the stack, keeping .env,
# certificates and data. See deploy/aws/README.md for the AWS-side setup.
set -euo pipefail

DOMAIN="" EMAIL="" REPO="https://github.com/vzc574/SIEM.git" BRANCH="master" DIR="/opt/siem"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --email) EMAIL="$2"; shift 2 ;;
    --repo) REPO="$2"; shift 2 ;;
    --branch) BRANCH="$2"; shift 2 ;;
    --dir) DIR="$2"; shift 2 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die() { echo "error: $*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run with sudo"
[[ -n "$DOMAIN" && -n "$EMAIL" ]] || die "--domain and --email are required (the domain's DNS A record must point at this instance)"
. /etc/os-release
[[ "$ID" == "ubuntu" ]] || die "this script supports Ubuntu (found $ID)"

COMPOSE=(docker compose -f docker-compose.yml -f docker-compose.secure.yml --profile agent)

log "Installing Docker, git and certbot"
apt-get update -q
apt-get install -y -q ca-certificates curl git certbot ufw
if ! command -v docker >/dev/null; then
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -q
  apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
systemctl enable --now docker

log "Fetching the SIEM ($BRANCH) into $DIR"
if [[ -d "$DIR/.git" ]]; then
  git -C "$DIR" fetch --quiet origin "$BRANCH"
  git -C "$DIR" checkout --quiet "$BRANCH"
  git -C "$DIR" pull --quiet --ff-only origin "$BRANCH"
else
  git clone --quiet --branch "$BRANCH" "$REPO" "$DIR"
fi
cd "$DIR"

if [[ ! -f .env ]]; then
  log "Generating secrets in $DIR/.env"
  key() { openssl rand -base64 36 | tr -d '/+=' | cut -c1-40; }
  umask 077
  cat > .env <<EOF
# Generated by setup-ec2.sh on $(date -u +%FT%TZ). Keep this file private.
# Admin API key for scripts; sign in to the dashboard with a user instead.
SIEM_API_KEYS=admin:$(key)=admin,remote-collector:$(key)=ingest
SIEM_NOTIFY_MIN_SEVERITY=high
# Fill in any of these to get alerts (see .env.example):
SIEM_SLACK_WEBHOOK_URL=
SIEM_TELEGRAM_BOT_TOKEN=
SIEM_TELEGRAM_CHAT_ID=
SIEM_SMTP_HOST=
SIEM_SMTP_PORT=587
SIEM_SMTP_USER=
SIEM_SMTP_PASSWORD=
SIEM_SMTP_FROM=
SIEM_SMTP_TO=
EOF
  umask 022
fi
chmod 600 .env

log "Firewall: allow SSH, HTTP and HTTPS only"
ufw allow OpenSSH >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw --force enable >/dev/null

log "TLS certificate for $DOMAIN (Let's Encrypt)"
install -d -m 0750 deploy/certs
if [[ ! -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ]]; then
  "${COMPOSE[@]}" stop proxy 2>/dev/null || true   # standalone mode needs port 80
  certbot certonly --standalone --non-interactive --agree-tos -m "$EMAIL" -d "$DOMAIN"
fi
install -m 0644 "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" deploy/certs/fullchain.pem
install -m 0600 "/etc/letsencrypt/live/$DOMAIN/privkey.pem" deploy/certs/privkey.pem
# Renewal: free port 80 briefly, then install the new certificate and restart nginx.
install -d /etc/letsencrypt/renewal-hooks/pre /etc/letsencrypt/renewal-hooks/deploy /etc/letsencrypt/renewal-hooks/post
printf '#!/bin/sh\ncd %q && docker compose -f docker-compose.yml -f docker-compose.secure.yml stop proxy\n' "$DIR" \
  > /etc/letsencrypt/renewal-hooks/pre/siem.sh
printf '#!/bin/sh\ninstall -m 0644 "$RENEWED_LINEAGE/fullchain.pem" %q/deploy/certs/fullchain.pem\ninstall -m 0600 "$RENEWED_LINEAGE/privkey.pem" %q/deploy/certs/privkey.pem\n' "$DIR" "$DIR" \
  > /etc/letsencrypt/renewal-hooks/deploy/siem.sh
printf '#!/bin/sh\ncd %q && docker compose -f docker-compose.yml -f docker-compose.secure.yml start proxy\n' "$DIR" \
  > /etc/letsencrypt/renewal-hooks/post/siem.sh
chmod 0755 /etc/letsencrypt/renewal-hooks/{pre,deploy,post}/siem.sh

log "Building and starting the stack (API, worker, auth.log agent, nginx)"
"${COMPOSE[@]}" up -d --build

log "Daily database backups to /var/backups/siem (14 days kept)"
install -d -m 0700 /var/backups/siem
cat > /etc/cron.daily/siem-backup <<EOF
#!/bin/sh
set -e
cd $DIR
stamp=\$(date +%F)
docker compose exec -T siem python database.py backup data/siem.db data/backup-\$stamp.db >/dev/null
# Only keep backups that pass SQLite's integrity check.
docker compose exec -T siem python database.py verify data/backup-\$stamp.db >/dev/null
docker compose cp siem:/app/data/backup-\$stamp.db /var/backups/siem/siem-\$stamp.db
docker compose exec -T siem rm -f data/backup-\$stamp.db
find /var/backups/siem -name 'siem-*.db' -mtime +14 -delete
EOF
chmod 0755 /etc/cron.daily/siem-backup

log "Waiting for the API"
for _ in $(seq 60); do
  curl -fsk "https://127.0.0.1/health" -H "Host: $DOMAIN" >/dev/null 2>&1 && break
  sleep 2
done
curl -fsk "https://127.0.0.1/health" -H "Host: $DOMAIN" >/dev/null || die "the API did not become healthy; check: cd $DIR && docker compose logs"

if ! "${COMPOSE[@]}" exec -T siem python database.py user-list | grep -q .; then
  if [[ -t 0 ]]; then
    log "Create the first dashboard admin"
    "${COMPOSE[@]}" exec siem python database.py user-add admin --role admin
  else
    echo "No dashboard user yet. Create one with:"
    echo "  cd $DIR && sudo docker compose exec siem python database.py user-add admin --role admin"
  fi
fi

log "Done"
cat <<EOF
Dashboard:  https://$DOMAIN/
Secrets:    $DIR/.env (API keys, notification settings - edit, then: sudo docker compose up -d)
Logs:       cd $DIR && sudo docker compose logs -f worker
Backups:    /var/backups/siem (daily)
Collectors: remote Linux/Windows hosts use the 'remote-collector' ingest key from .env
EOF
